// The commands opossum's output suggests are held to what they say: each is
// taken as printed, handed to a shell, and run — and the run it starts has to
// read the project the run that printed it read, and reach what it made.
// Everything here goes through shellReads (composefile_test.go).

// Where opossum wrote the overlay and this run found more, the way to have it
// rewritten is said as a command — and the rewrite looks only at the services
// the run enables, so it has to be the run that found these. A profile may now
// come from an `--env-file`, which a shell does not carry over as it does
// COMPOSE_PROFILES: the command has to. Each row follows the command as printed
// and asks whether that run still sees what this one reported.
func TestTheRewriteTheAdviceNamesSeesWhatThisRunSaw(t *testing.T) {
	const compose = "services:\n  base:\n    image: alpine:3\n" +
		"  extra:\n    image: alpine:3\n    profiles: [extras]\n    volumes: [\"shared:/data\"]\n" +
		"  worker:\n    image: alpine:3\n    profiles: [extras]\n    volumes: [\"shared:/data\"]\n" +
		"volumes:\n  shared: {}\n"
	for _, tc := range []struct {
		name  string
		args  []string
		shell *string
		// files are written beside the compose file: name and body.
		files map[string]string
		// named are the services the run names, after the subcommand's flags.
		named []string
		// wantCommand is a part of the command as printed.
		wantCommand string
	}{
		{name: "the profile from an --env-file", args: []string{"--env-file", "cf.env"},
			files: map[string]string{"cf.env": "COMPOSE_PROFILES=extras\n"}, wantCommand: " --env-file cf.env"},
		{name: "from an --env-file a shell would take apart", args: []string{"--env-file", "my env/cf.env"},
			files: map[string]string{"my env/cf.env": "COMPOSE_PROFILES=extras\n"}, wantCommand: " --env-file 'my env/cf.env'"},
		// --env-file repeats and the later file wins: all of them, in order. Here
		// only the last one says anything.
		{name: "from the later of two --env-files", args: []string{"--env-file", "quiet.env", "--env-file", "cf.env"},
			files:       map[string]string{"quiet.env": "COMPOSE_PROFILES=\n", "cf.env": "COMPOSE_PROFILES=extras\n"},
			wantCommand: " --env-file quiet.env --env-file cf.env"},
		{name: "from the flag", args: []string{"--profile", "extras"}, wantCommand: " --profile extras"},
		// The project's name and the DNS domain are in the names of what the
		// run made: a rewrite without them would be another project's.
		{name: "with the project's name", args: []string{"-p", "my proj", "--profile", "extras"}, wantCommand: " -p 'my proj' --profile extras"},
		{name: "with the DNS domain", args: []string{"--dns-domain", "foo", "--profile", "extras"}, wantCommand: " --profile extras --dns-domain foo"},
		// The services the run named are named again — and here they are all
		// that enables extra and worker, so a rewrite without them sees nothing.
		{name: "with the services it named", named: []string{"extra", "worker"},
			wantCommand: " extra worker"},
		// The shell's and the `.env`'s need no repeating: the rewrite runs with both.
		{name: "from the shell", shell: ptr("extras")},
		{name: "from the .env", files: map[string]string{".env": "COMPOSE_PROFILES=extras\n"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			fakeShim(t)
			t.Setenv("XDG_STATE_HOME", t.TempDir())
			root := t.TempDir()
			dir := filepath.Join(root, "proj")
			if err := os.MkdirAll(dir, 0o755); err != nil {
				t.Fatal(err)
			}
			write(t, filepath.Join(dir, "compose.yaml"), compose)
			for name, body := range tc.files {
				if err := os.MkdirAll(filepath.Dir(filepath.Join(dir, name)), 0o755); err != nil {
					t.Fatal(err)
				}
				write(t, filepath.Join(dir, name), body)
			}
			t.Chdir(dir)
			for _, name := range []string{"COMPOSE_PROJECT_NAME", "COMPOSE_PATH_SEPARATOR", "COMPOSE_FILE"} {
				setOrUnset(t, name, nil)
			}
			setOrUnset(t, "COMPOSE_PROFILES", tc.shell)
			// An overlay opossum wrote, by a run that found less than this one will.
			write(t, filepath.Join(dir, "compose.opossum.yaml"), "# Generated by `opossum up --from-docker-compose`.\nservices: {}\n")

			const saw = `service "extra" shares named volume`
			first := append(append([]string{}, tc.args...), "up", "--from-docker-compose", "--no-build", "--dry-run")
			_, stderr, err := runSplit(t, append(first, tc.named...)...)
			if err != nil {
				t.Fatalf("up --from-docker-compose: %v\n%s", err, stderr)
			}
			_, rest, ok := strings.Cut(stderr, "was generated by opossum, so `")
			if !ok || !strings.Contains(stderr, saw) {
				t.Fatalf("this fixture should have the run find more than the overlay holds and say how to rewrite it; got:\n%s", stderr)
			}
			command, _, _ := strings.Cut(rest, "` rewrites it")
			if !strings.HasSuffix(command, "opossum up --from-docker-compose"+tc.wantCommand) {
				t.Errorf("the command should end %q, got: %s", "opossum up --from-docker-compose"+tc.wantCommand, command)
			}
			_, argv := shellReads(t, root, command)
			if _, err := os.Stat(filepath.Join(dir, "compose.opossum.yaml")); err == nil {
				t.Fatalf("the command should have removed the overlay: %s", command)
			}
			// The flags this adds go before the services the command names.
			at := len(argv) - len(tc.named)
			followed := append(append(append([]string{}, argv[:at]...), "--no-build", "--dry-run"), argv[at:]...)
			_, stderr2, err := runSplit(t, followed...)
			if err != nil {
				t.Fatalf("following the advice (%s) failed: %v\n%s", command, err, stderr2)
			}
			if !strings.Contains(stderr2, saw) {
				t.Errorf("the rewrite (%s) does not see what this run reported; got:\n%s", command, stderr2)
			}
			// …and it is the same project: the name it would make things under.
			before, err := run(t, append(append([]string{}, tc.args...), "config")...)
			if err != nil {
				t.Fatal(err)
			}
			// The command's root flags come after `up --from-docker-compose`.
			flags := argv[2:at]
			after, err := run(t, append(append([]string{}, flags...), "config")...)
			if err != nil {
				t.Fatalf("config with the command's flags (%v): %v", flags, err)
			}
			if configName(before) != configName(after) {
				t.Errorf("the rewrite reads project %q where this run read %q", configName(after), configName(before))
			}
		})
	}
}

// A `--profile` that names nothing is still the flag — it keeps
// COMPOSE_PROFILES from being read — so a command that repeats a run's flags
// repeats that one too.
func TestProfileFlagsSpellsAnEmptyProfile(t *testing.T) {
	if got, want := profileFlags([]string{"", "a b", " c "}), " --profile '' --profile 'a b' --profile c"; got != want {
		t.Errorf("profileFlags = %q, want %q", got, want)
	}
}

// A service name opossum takes may be one a shell would take apart (docker
